"""구역 7 (잿빛 전장: 잿빛 인형극)·구역 8 (노르딘 왕성: 얼어붙은 안식) — 새 기획 D-085: 해금 순서, 배경, 새 적 행동
(철조망 장벽·곡사 수류탄·가스 구름·기관총 연사·호루라기 광폭화·소환·지뢰 / 화상 반사·끓는 기름·덫·조각상 해동·증기 자폭·열광선),
7-B 베헤모스(철갑탄·소이탄·돌진)·조명탄, 8-B 블라디미르(숨결·유성우·온기 강탈)·탐욕의 제단"""

from test_zone34 import CLEAR, CLEAN, BG, battle_at, place


def boss_at(g, stage):
    battle_at(g, stage)
    g.js("b.midBaseSpawned = true; b.midBaseDestroyed = true; b.distanceTraveled = b.stage.finalAt - 0.5; b.playerSpeed = 100;")
    g.wait(2600)
    g.js(CLEAN + "b.monsterX = 420; m.setMonsterPosition(420); b.boss.x = 780; b.boss.dom.style.left = '780px'; b.boss.speed = 0;"
         "Object.keys(b.boss.cd).forEach(k => b.boss.cd[k] = -99);")


def run(ctx):
    g = ctx.game(fresh=True)
    g.enter_v2()

    # 해금: 6-B → 7-1, 7-B → 8-1, 8-B → 9-1
    g.js(CLEAR.replace('IDS', '[1, 2, 3, 4, 5, 6]') + "window.madOverlordGameV2.menuController.renderStages();")
    st = g.js("""document.querySelector('#menu-zones-v2 .v2-zonetab[data-zone="ch7"]').click();
        const S = await import('/js/engine_v2/stages_v2.js');
        return { sel: progress.selectedStage, n7: S.CHAPTER7.stages.length, n8: S.CHAPTER8.stages.length,
                 a6: S.nextStageOf('6-B').id, a7: S.nextStageOf('7-B').id, a8: S.nextStageOf('8-B').id,
                 z8: document.querySelector('#menu-zones-v2 .v2-zonetab[data-zone="ch8"]').classList.contains('is-locked') };""")
    ctx.check(st['sel'] == '7-1' and st['n7'] == 11 and st['n8'] == 11 and st['a6'] == '7-1' and st['a7'] == '8-1' and st['a8'] == '9-1' and st['z8'],
              '6-B 클리어 → 구역 7 열림(7-1), 11판씩, 7-B 다음 = 8-1, 8-B 다음 = 9-1, 구역 8은 잠김', str(st))

    # ---- 구역 7 ----
    battle_at(g, '7-1')
    place(g, 'trench', 300)
    st = g.js(BG + "const e = b.enemies.find(e => e.type === 'trench'); return { zone: sc.classList.contains('v2-zone-7'), sky: bg('sky'), ground: bg('ground'), img: getComputedStyle(e.dom.querySelector('.v2-enemy__sprite')).backgroundImage };")
    ctx.check(st['zone'] and 'st7/far.webp' in st['sky'] and 'st7/floor.webp' in st['ground'] and 'trench_walk' in st['img'], '구역 7 배경 + 참호 징집병 그림', str(st))
    place(g, 'wireshield', 260, 'e.cd.build = 99;')
    g.wait(1600)
    ctx.check(g.js("return b.enemies.some(e => e.isBarricade && e.art === 'st7_barr');"), '철조망 방패병: 철조망 장벽')
    place(g, 'grenadier', 260, 'e.cd.skill = 99;')
    g.wait(1600)
    ctx.check(g.js("return b._hurt;") > 0, '유산탄 투척병: 곡사 수류탄 피해')
    place(g, 'gassoldier', 220, 'e.cd.skill = 99;')
    g.wait(1500)
    ctx.check(g.js("return b.hazards.length >= 1 && (b.pSlowT > 0 || b.pStatusShown === 'slow');"), '독가스 살포병: 노란 가스 구름 → 감속')
    place(g, 'mgnest', 400, 'e.cd.skill = 99;')
    g.wait(1200)
    ctx.check(g.js("return b._hurt;") > 0, '야전 기관총 좌: 연사 피해')
    place(g, 'officer', 300, "e.cd.rally = 99; const s = b.spawnMinion('trench', { x: b.frontX() + 340, elite: false }); s.speed = 0;")
    g.wait(400)
    st = g.js("const s = b.enemies.filter(e => e.type === 'trench'); return { n: s.length, haste: s.some(e => e.hasteUntil > b.stats.time) };")
    ctx.check(st['n'] >= 4 and st['haste'], '돌격 장교: 호루라기 → 주변 광폭화 + 참호 보병 3~5명 소환', str(st))
    place(g, 'sapper', 260, 'e.cd.skill = 99;')
    g.wait(900)
    st = g.js("return { mines: b.hazards.filter(h => h.mine).length, cls: document.querySelectorAll('.v2-puddle--mine').length };")
    ctx.check(st['mines'] >= 1 and st['cls'] >= 1, '지뢰 매설병: 앞길에 지뢰를 묻음', str(st))
    g.js("const h = b.hazards.find(h => h.mine); h.x = b.monsterX + 40; h.dom.style.left = h.x + 'px'; b._hurt = 0;")
    g.wait(300)
    st = g.js("return { stun: b.pStunT > 0, hurt: b._hurt, left: b.hazards.filter(h => h.mine).length };")
    ctx.check(st['stun'] and st['hurt'] > 0, '지뢰를 밟으면 피해 + 기절', str(st))
    g.shot('zone7_enemies', '#screen-battle-v2')

    g.js("b.stopBattle();" + CLEAR.replace('IDS', '[1, 2, 3, 4, 5, 6, 7]'))
    boss_at(g, '7-B')
    st = g.js("const f = b.enemies.find(e => e.isFinal); return { art: f && f.art, boss: b.boss && b.boss.type };")
    ctx.check(st['art'] == 'st7_base' and st['boss'] == 'behemoth', '7-B: 전방 사령탑 · 심판의 구포 베헤모스', str(st))
    g.js("b.boss.cd.cannon = b.boss.t.cannon.every - 0.05;")
    g.wait(1700)
    st = g.js("return { hurt: b._hurt, x: b.monsterX };")
    ctx.check(st['hurt'] > 0 and st['x'] < 420, '철갑탄 직사: 피해 + 밀려남', str(st))
    g.js("b._hurt = 0; b.boss.cd.cannon = -99; b.boss.cd.incendiary = b.boss.t.incendiary.every - 0.05;")
    g.wait(1900)
    ctx.check(g.js("return b.hazards.filter(h => h.fire > 0).length;") >= 2, '백린 소이탄: 불 장판 여러 개')
    g.js("b.boss.cd.incendiary = -99; b.monsterX = 420; m.setMonsterPosition(420); b._hurt = 0; b.boss.cd.treadCharge = b.boss.t.treadCharge.every - 0.05;")
    g.wait(1500)
    st = g.js("return { hurt: b._hurt, bx: b.boss.x };")
    ctx.check(st['hurt'] > 0 and st['bx'] < 700, '궤도 톱니 돌진: 주인공 앞까지 밀고 들어옴', str(st))
    # 조명탄: 부수면 끝 / 못 부수면 융단 포격
    g.js("b.hazards.forEach(h => h.dom.remove()); b.hazards = []; b.boss.cd.treadCharge = -99; b._hurt = 0; b.flareTimer = b.stage.boss.flares.every - 0.05;")
    g.wait(300)
    st = g.js("const f = b.enemies.find(e => e.type === 'flare'); return f ? { fly: parseFloat(f.dom.style.bottom), cls: f.dom.classList.contains('v2-flare') } : null;")
    ctx.check(bool(st) and st['fly'] > 200 and st['cls'], '조명탄: 하늘에 붉은 조명탄이 뜸', str(st))
    g.shot('zone7_flare', '#screen-battle-v2')
    g.js("const f = b.enemies.find(e => e.type === 'flare'); b.dealDamageToEnemy(f, f.hp + 10, false); b._hurt = 0; b.flareTimer = 0;")
    g.wait(300)
    ctx.check(g.js("return !b.enemies.some(e => e.type === 'flare') && b._hurt === 0;"), '조명탄을 부수면 포격 없음')
    g.js("b.flareTimer = b.stage.boss.flares.every - 0.05;")
    g.wait(300)
    g.js("const f = b.enemies.find(e => e.type === 'flare'); f.fuseAt = b.stats.time + 0.1; b._hurt = 0;")
    g.wait(600)
    st = g.js("return { hurt: b._hurt, want: b.maxPlayerHp * b.stage.boss.flares.dmg };")
    ctx.check(st['hurt'] >= st['want'] * 0.99, '조명탄을 못 부수면 융단 포격 (최대 내구도 22%)', str(st))

    # ---- 구역 8 ----
    g.js("b.stopBattle();" + CLEAR.replace('IDS', '[1, 2, 3, 4, 5, 6, 7]'))
    battle_at(g, '8-1')
    place(g, 'torch', 300)
    st = g.js(BG + "return { zone: sc.classList.contains('v2-zone-8'), sky: bg('sky'), ground: bg('ground') };")
    ctx.check(st['zone'] and 'st8/far.webp' in st['sky'] and 'st8/floor.webp' in st['ground'], '구역 8 배경 (눈보라 왕성)', str(st))
    place(g, 'furnaceshield', 300)
    st = g.js("const e = b.enemies.find(e => e.type === 'furnaceshield'); b._hurt = 0; b.dealDamageToEnemy(e, 400, false, { knock: 0 }); return { hurt: b._hurt };")
    ctx.check(st['hurt'] > 0, '화로 방패병: 때리면 근접 화상 반사', str(st))
    place(g, 'oilthrower', 230, 'e.cd.skill = 99;')
    g.wait(1500)
    ctx.check(g.js("return b.hazards.some(h => h.fire > 0) && b._hurt > 0;"), '끓는 기름 투척병: 불 장판 위에서 지속 피해')
    place(g, 'hunter', 260, 'e.cd.skill = 99;')
    g.wait(1200)
    ctx.check(g.js("return b.pRootT;") > 1, '작살총 사냥꾼: 강철 덫 속박')
    place(g, 'heatshaman', 360)
    g.wait(300)
    st = g.js("return b.enemies.filter(e => e.type === 'frozenstatue').length;")
    ctx.check(3 <= st <= 5, '열기 주술사: 얼어붙은 병사 조각상 3~5기와 함께 나옴', str(st))
    g.js("const s = b.enemies.find(e => e.type === 'heatshaman'); s.cd.thaw = 99;")
    g.wait(400)
    st = g.js("return { statues: b.enemies.filter(e => e.type === 'frozenstatue').length, units: b.enemies.filter(e => ['torch', 'furnaceshield', 'oilthrower', 'hunter'].includes(e.type)).length };")
    ctx.check(st['statues'] == 0 and st['units'] >= 3, '해동: 조각상이 녹아 적으로 깨어남', str(st))
    g.shot('zone8_thaw', '#screen-battle-v2')
    g.js(CLEAN + "b.spawnMinion('steambomber', { x: b.frontX() + 30, elite: false });")
    g.wait(400)
    st = g.js("return { hurt: b._hurt, slow: b.pSlowT > 0, alive: b.enemies.some(e => e.type === 'steambomber') };")
    ctx.check(st['hurt'] > 0 and st['slow'] and not st['alive'], '증기 돌파병: 자폭 → 피해 + 수증기 감속', str(st))
    g.js(CLEAN + "window.__cd0 = { ...b.skillCd }; const e = b.spawnMinion('heatturret', { x: b.frontX() + 360, elite: false }); e.speed = 0; e.cd.skill = 99;")
    g.wait(1000)
    cd = g.js("return { before: window.__cd0, after: { ...b.skillCd } };")
    ctx.check(any(cd['after'].get(k, 0) > cd['before'].get(k, 0) + 0.3 for k in ('arm', 'body') if k in cd['before']), '열광선 포탑: 스킬 쿨다운 늘림', str(cd))

    g.js("b.stopBattle();" + CLEAR.replace('IDS', '[1, 2, 3, 4, 5, 6, 7, 8]'))
    boss_at(g, '8-B')
    st = g.js("const f = b.enemies.find(e => e.isFinal); return { art: f && f.art, boss: b.boss && b.boss.type };")
    ctx.check(st['art'] == 'st8_base' and st['boss'] == 'vladimir', '8-B: 메인 화로석 제단 · 블라디미르 국왕', str(st))
    g.js("b.boss.cd.laser = b.boss.t.laser.every - 0.05;")
    g.wait(1700)
    ctx.check(g.js("return b._hurt;") > 0, '화룡의 숨결: 조준 뒤 불 브레스 피해')
    g.js("b._hurt = 0; b.boss.cd.laser = -99; b.boss.cd.heatSteal = b.boss.t.heatSteal.every - 0.05; b.boss.shield = 0;")
    g.wait(1600)
    st = g.js("return { stun: b.pStunT > 0, shield: b.boss.shield > 0 };")
    ctx.check(st['stun'] and st['shield'], '온기 강탈: 빙결(기절) + 화염 보호막', str(st))
    g.js("b.pStunT = 0; b.boss.cd.heatSteal = -99; b.boss.shield = 0; window.__dps = b.boss.dps; b.altarTimer = b.stage.boss.altars.every - 0.05;")
    g.wait(400)
    st = g.js("return { n: b.enemies.filter(e => e.isAltar).length, dps: b.boss.dps > window.__dps };")
    ctx.check(st['n'] == 3 and st['dps'], '탐욕의 제단: 제단 3개 + 국왕 공격력 상승', str(st))
    g.js("b._hurt = 0;")
    g.wait(800)
    ctx.check(g.js("return b._hurt;") > 0, '제단이 서 있는 동안 열파동 지속 피해')
    g.shot('zone8_altars', '#screen-battle-v2')
    g.js("b.enemies.filter(e => e.isAltar).forEach(a => b.dealDamageToEnemy(a, a.hp + 10, false));")
    g.wait(300)
    st = g.js("return { stun: b.boss.stunT > 0, dps: Math.abs(b.boss.dps - window.__dps) < 0.01 };")
    ctx.check(st['stun'] and st['dps'], '제단을 모두 부수면 국왕 기절 + 공격력 원래대로', str(st))
